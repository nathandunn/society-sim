// Build: copy the engine into public/src so the static site is self-contained,
// and stamp the version (package version + git commit + build date) into public/version.js.
import { cpSync, mkdirSync, rmSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const out = new URL('public/src/', root);
if (existsSync(out)) rmSync(out, { recursive: true });
mkdirSync(out, { recursive: true });
for (const f of ['engine.js', 'genome.js', 'params.js', 'sweep.js', 'world.js']) cpSync(new URL('src/' + f, root), new URL(f, out));

// read the commit without needing git installed (the Docker build has no git binary)
function commit() {
  try {
    const gitDir = new URL('.git/', root);
    const head = readFileSync(new URL('HEAD', gitDir), 'utf8').trim();
    if (!head.startsWith('ref: ')) return head.slice(0, 7);
    const ref = head.slice(5);
    if (existsSync(new URL(ref, gitDir))) return readFileSync(new URL(ref, gitDir), 'utf8').trim().slice(0, 7);
    const packed = readFileSync(new URL('packed-refs', gitDir), 'utf8').split('\n').find(l => l.endsWith(' ' + ref));
    return packed ? packed.slice(0, 7) : 'unknown';
  } catch { return 'unknown'; }
}
const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const v = { version: pkg.version, commit: commit(), built: new Date().toISOString().slice(0, 10) };
writeFileSync(new URL('public/version.js', root), `// generated by tools/build.mjs\nexport const BUILD = ${JSON.stringify(v)};\n`);
console.log(`built public/ v${v.version} (${v.commit}, ${v.built})`);
